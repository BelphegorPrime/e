// Bundles the egress API (src/egress/server.ts) into one dependency-free ESM
// script and writes it as a string constant to src/egress/bundle.generated.ts,
// so `e init` can seed it into the egress build context without reading any
// file at run time (which keeps the pkg binary self-contained). Runs before
// tsc in `build:ts`; tsc still type-checks the sources afterwards.
//
// Why bundle rather than copy tsc output: the container has no node_modules
// and no package.json, so cross-file ESM imports would need a rewrite anyway.

import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'src', 'egress', 'server.ts');
const target = path.join(root, 'src', 'egress', 'bundle.generated.ts');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  // Node built-ins only; anything else would silently be inlined into the
  // container script, so fail loudly instead.
  packages: 'external',
  legalComments: 'none',
});

const code = result.outputFiles[0].text;
const external = [...code.matchAll(/^import\s.*?from\s+["']([^"']+)["']/gm)]
  .map(m => m[1])
  .filter(spec => !spec.startsWith('node:'));
if (external.length > 0) {
  throw new Error(
    `egress API bundle must only import node built-ins, found: ${external.join(', ')}`
  );
}

const generated = `// GENERATED by scripts/build-egress-api.mjs from src/egress/server.ts.
// Do not edit; rebuild with \`npm run build:egress-api\`.
/* eslint-disable */
/** The self-contained egress API script seeded into the egress build context. */
export const EGRESS_API_BUNDLE: string = ${JSON.stringify(code)};
`;
await fs.writeFile(target, generated);
console.log(`egress API bundle written to ${path.relative(root, target)}`);
